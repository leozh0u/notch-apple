import Foundation

let now = Date(timeIntervalSince1970: 1_000)
var timer = FocusCountdown()
assert(timer.remaining == 1500 && !timer.isRunning && !timer.isFinished)
timer.start(at: now)
let deadline = timer.deadline
timer.start(at: now.addingTimeInterval(50))
assert(timer.deadline == deadline, "Starting twice must not move the deadline")
timer.tick(at: now.addingTimeInterval(62))
assert(timer.remaining == 1438 && timer.isRunning)
timer.pause(at: now.addingTimeInterval(70))
assert(timer.remaining == 1430 && !timer.isRunning)
timer.tick(at: now.addingTimeInterval(500))
assert(timer.remaining == 1430, "Paused time must not elapse")
timer.start(at: now.addingTimeInterval(500))
timer.tick(at: now.addingTimeInterval(2000))
assert(timer.isFinished && !timer.isRunning && timer.remaining == 0, "Sleep past the deadline must finish once")
timer.tick(at: now.addingTimeInterval(2500))
assert(timer.isFinished)
timer.start(at: now.addingTimeInterval(3000))
assert(timer.remaining == 1500 && timer.isRunning, "Starting after completion starts a fresh session")
timer.reset(minutes: 15)
assert(timer.duration == 900 && timer.remaining == 900 && !timer.isRunning)
timer.reset(minutes: -1)
assert(timer.duration == 900, "Invalid durations must not corrupt the timer")
timer.reset(minutes: 45)
assert(timer.remaining == 2700)
timer.reset(seconds: 95)
assert(timer.duration == 95 && timer.remaining == 95, "Custom minutes and seconds must stay exact")
timer.start(at: now)
timer.pause(at: now.addingTimeInterval(5))
assert(timer.remaining == 90)
timer.start(at: now.addingTimeInterval(10))
timer.tick(at: now.addingTimeInterval(100))
assert(timer.isFinished && timer.remaining == 0, "A resumed exact duration must finish on its deadline")
timer.reset(seconds: 1)
assert(timer.duration == 1 && timer.remaining == 1)
timer.start(at: now)
let minimumDeadline = timer.deadline
for invalid in [0, -1, 43_201, Int.max, Int.min] {
    timer.reset(seconds: invalid)
    assert(timer.duration == 1 && timer.deadline == minimumDeadline, "Invalid seconds must leave an active timer intact")
}
timer.tick(at: now.addingTimeInterval(1))
assert(timer.isFinished)
timer.reset(seconds: 43_200)
assert(timer.duration == 43_200 && timer.remaining == 43_200, "Allow exactly twelve hours")
timer.reset(minutes: Int.max)
assert(timer.duration == 43_200, "Invalid minutes must not overflow or change the duration")
timer.reset(minutes: 25)
assert(timer.duration == 1500, "Keep the original minutes API")
print("Focus countdown checks passed: deadlines, pause/resume, restart, reset, exact seconds and validation bounds.")
